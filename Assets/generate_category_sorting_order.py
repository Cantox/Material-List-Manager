#!/usr/bin/env python3
"""
ordering.py - Minecraft Creative inventory ordering extractor (26.x, unobfuscated sources)

Reads the decompiled game sources and writes creative_order.json: {"minecraft:item_id": position}
reproducing the order of the "Search Items" (compass) tab of the Creative inventory.
Sorting any list of item/block ids by this position gives the in-game order.

USAGE
  python ordering.py -i ".../net/minecraft/" -o "output/folder"
  Optional: --registry registries.json   check every id against the game's real item registry
            --no-namespace               write "oak_log" instead of "minecraft:oak_log"
            --exclude-tab NAME           drop a tab (repeatable), e.g. op_blocks

FILES USED (found automatically anywhere under the input folder)
  world/item/CreativeModeTabs.java    tab order + item order inside each tab
  world/item/Items.java               Items.X constant -> id symbol
  references/BlockItemIds.java        id strings for blocks/items
  references/ItemIds.java             id strings for plain items
  world/level/block/ColorCollection.java, WeatheringCopperCollection.java   (optional) orderings/prefixes

HOW THE GAME BUILDS THE SEARCH TAB (replicated here)
  - Tabs are visited in registration order (order of the Registry.register calls).
  - Inside a tab, items follow the order of the displayItems lambda.
  - An item already added by an earlier tab is not added again (first occurrence wins).
  - Items added with TabVisibility.PARENT_TAB_ONLY are not shown in the search tab.
  - Hotbar, Inventory and Search tabs contribute nothing.

KNOWN LIMITS
  - Items generated by code (potions, tipped arrows, enchanted books, suspicious stews, ominous bottles,
    goat horns, paintings, fireworks, ...) are not single ids and are skipped. Positions are ordinal among
    the captured items, so the relative order of everything captured is exact.
  - Spawn eggs, music discs, pottery sherds and armor-trim templates are declared through helper calls
    (createSpawnEgg(...) etc.); their id is taken from the constant name, which matches the id by convention.
"""
import argparse
import json
import re
import sys
from pathlib import Path

SKIP_TAB_KEYWORDS = ("hotbar", "inventory", "search")

DEFAULT_COLOR_FOREACH = ["white", "orange", "magenta", "light_blue", "yellow", "lime", "pink",
                         "gray", "light_gray", "cyan", "purple", "blue", "brown", "green", "red", "black"]
DEFAULT_WEATHERING_PREFIXES = ["", "exposed_", "weathered_", "oxidized_"]
DEFAULT_WAXED_PREFIXES = ["waxed_", "waxed_exposed_", "waxed_weathered_", "waxed_oxidized_"]

REGISTER_KEY = re.compile(r"register\(\s*[\w.]+\s*,\s*([A-Za-z_][\w.]*)\s*,")
TITLE_KEY = re.compile(r"itemGroup\.(\w+)")
CHAIN_STEP = re.compile(r"\s*\.\s*(\w+)\s*\(")
DECL = re.compile(r"public\s+static\s+final\s+[\w.]+(?:<[\w.<>?, ]*>)?\s+([A-Z][A-Z0-9_]*)\s*=")
ID_SYMBOL = re.compile(r"\b(BlockItemIds|ItemIds)\.([A-Z][A-Z0-9_]*)\b")
EVENT = re.compile(
    r"(?P<color>registerColoredItems\s*\(\s*\w+\s*,\s*\w+\s*,\s*Items\.(?P<color_c>[A-Z][A-Z0-9_]*)\s*\))"
    r"|(?P<fam>copperBlockFamilies\s*\(\s*\w+\s*->\s*\w+\.(?P<fam_k>weathering|waxed)\(\)\.forEach)"
    r"|(?P<ref>\b(?P<ns>Items|Blocks)\.(?P<name>[A-Z][A-Z0-9_]*)\b)"
)


# ------------------------------------------------------------------ generic parsing helpers
def strip_comments(src):
    """Remove // and /* */ comments while respecting string and char literals."""
    out, i, n = [], 0, len(src)
    while i < n:
        c = src[i]
        if c in "\"'":
            j = i + 1
            while j < n and src[j] != c:
                if src[j] == "\\":
                    j += 1
                j += 1
            out.append(src[i:j + 1])
            i = j + 1
        elif src.startswith("//", i):
            j = src.find("\n", i)
            i = n if j == -1 else j
        elif src.startswith("/*", i):
            j = src.find("*/", i + 2)
            i = n if j == -1 else j + 2
        else:
            out.append(c)
            i += 1
    return "".join(out)


def matching(src, start, open_c="(", close_c=")"):
    """Index of the bracket closing the one at src[start]."""
    depth, i, n = 0, start, len(src)
    while i < n:
        c = src[i]
        if c in "\"'":
            i += 1
            while i < n and src[i] != c:
                if src[i] == "\\":
                    i += 1
                i += 1
        elif c == open_c:
            depth += 1
        elif c == close_c:
            depth -= 1
            if depth == 0:
                return i
        i += 1
    raise ValueError("unbalanced brackets in source")


def statement_end(src, start):
    """Index of the ';' ending the statement that starts at `start` (depth 0)."""
    depth, i, n = 0, start, len(src)
    while i < n:
        c = src[i]
        if c in "\"'":
            i += 1
            while i < n and src[i] != c:
                if src[i] == "\\":
                    i += 1
                i += 1
        elif c in "({[":
            depth += 1
        elif c in ")}]":
            depth -= 1
        elif c == ";" and depth <= 0:
            return i
        i += 1
    return n


def camel_to_snake(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def method_chain(body, pos):
    """Read a call chain like .a(...).b(...) starting at pos. Returns ([names], position_after)."""
    names = []
    while True:
        m = CHAIN_STEP.match(body, pos)
        if not m:
            return names, pos
        names.append(m.group(1))
        pos = matching(body, m.end() - 1) + 1


def read_java(path):
    return strip_comments(path.read_text(encoding="utf-8"))


def find_source(root, filename, near=None):
    """Find filename under root. Prefer the file next to `near`, then the shallowest path."""
    candidates = list(root.rglob(filename))
    if not candidates:
        return None
    candidates.sort(key=lambda p: (near is None or p.parent != near.parent, len(p.parts), str(p)))
    return candidates[0]


# ------------------------------------------------------------------ orderings from the collection classes
def parse_color_foreach(path):
    if path is None:
        return DEFAULT_COLOR_FOREACH, "default"
    src = read_java(path)
    m = re.search(r"void\s+forEach\s*\([^)]*\)\s*\{", src)
    if m:
        end = matching(src, m.end() - 1, "{", "}")
        names = [camel_to_snake(n) for n in re.findall(r"consumer\.accept\(this\.(\w+)\)", src[m.end():end])]
        if len(names) == 16:
            return names, "ColorCollection.java"
    return DEFAULT_COLOR_FOREACH, "default (could not parse ColorCollection.java)"


def parse_copper_prefixes(path):
    """Returns ({'weathering': [...4], 'waxed': [...4]}, forEach order tuple, source)."""
    weathering, waxed, order, source = DEFAULT_WEATHERING_PREFIXES, DEFAULT_WAXED_PREFIXES, ("weathering", "waxed"), "default"
    if path is not None:
        src = read_java(path)
        m = re.search(r"PREFIXES\s*=\s*new\s+WeatheringCopperCollection<>\(\s*new\s+WeatheringCopperCollection\.ByState<>\(([^)]*)\)"
                      r"\s*,\s*new\s+WeatheringCopperCollection\.ByState<>\(([^)]*)\)", src, re.S)
        if m:
            w, x = re.findall(r'"([^"]*)"', m.group(1)), re.findall(r'"([^"]*)"', m.group(2))
            if len(w) == 4 and len(x) == 4:
                weathering, waxed, source = w, x, "WeatheringCopperCollection.java"
        a, b = src.find("this.weathering.forEach"), src.find("this.waxed.forEach")
        if a != -1 and b != -1 and b < a:
            order = ("waxed", "weathering")
    return {"weathering": weathering, "waxed": waxed}, order, source


# ------------------------------------------------------------------ id tables
# An entry is one of:
#   ("single", "item_id", exact?)
#   ("color",  {"white": "white_wool", ...}, exact?)
#   ("copper", {"weathering": [4 ids], "waxed": [4 ids]}, exact?)
def parse_block_item_ids(src, color_names, prefixes):
    special = {m.group(1): re.findall(r'"([^"]*)"', m.group(2))
               for m in re.finditer(r"ByState<String>\s+(\w+)\s*=\s*new\s+[\w.]+<>\(([^)]*)\)", src)}
    table = {}
    for m in DECL.finditer(src):
        sym, rhs = m.group(1), src[m.end():statement_end(src, m.end())]
        c = re.match(r'\s*BlockItemId\.create\(\s*"([^"]*)"(?:\s*,\s*"([^"]*)")?\s*\)', rhs)
        if c:
            table[sym] = ("single", c.group(2) or c.group(1), True)
            continue
        c = re.match(r'\s*createSimpleColored\(\s*"([^"]*)"\s*\)', rhs)
        if c:
            table[sym] = ("color", {col: f"{col}_{c.group(1)}" for col in color_names}, True)
            continue
        c = re.match(r'\s*createSimpleCopper\(\s*"([^"]*)"\s*\)', rhs)
        if c:
            names = [c.group(1)] * 4
            table[sym] = ("copper", copper_table(names, prefixes), True)
            continue
        c = re.search(r"prefixWithState\(\s*WeatheringCopperCollection\.same\(\s*(\w+)\s*\)", rhs)
        if c and c.group(1) in special and len(special[c.group(1)]) == 4:
            table[sym] = ("copper", copper_table(special[c.group(1)], prefixes), True)
    return table


def copper_table(names, prefixes):
    return {"weathering": [p + n for p, n in zip(prefixes["weathering"], names)],
            "waxed": [p + n for p, n in zip(prefixes["waxed"], names)]}


def parse_item_ids(src, color_names):
    table = {}
    for m in DECL.finditer(src):
        sym, rhs = m.group(1), src[m.end():statement_end(src, m.end())]
        c = re.match(r'\s*create\(\s*"([^"]*)"\s*\)', rhs)
        if c:
            table[sym] = ("single", c.group(1), True)
            continue
        c = re.match(r'\s*createSimpleColored\(\s*"([^"]*)"\s*\)', rhs)
        if c:
            table[sym] = ("color", {col: f"{col}_{c.group(1)}" for col in color_names}, True)
            continue
        if re.match(r"\s*create(SpawnEgg|MusicDisc|PotterySherd|ArmorTrimSmithingTemplate)\(", rhs):
            table[sym] = ("single", sym.lower(), False)     # id == constant name by convention
    return table


def parse_items_java(src):
    """Items.X constant -> (BlockItemIds|ItemIds, SYMBOL) of the id it is registered with."""
    mapping = {}
    for m in DECL.finditer(src):
        rhs = src[m.end():statement_end(src, m.end())]
        s = ID_SYMBOL.search(rhs)
        if s:
            mapping[m.group(1)] = (s.group(1), s.group(2))
    return mapping


class Resolver:
    def __init__(self, items_map, block_table, item_table):
        self.items_map, self.block_table, self.item_table = items_map, block_table, item_table
        self.fallbacks = set()

    def entry(self, const):
        ref = self.items_map.get(const)
        if ref:
            e = (self.block_table if ref[0] == "BlockItemIds" else self.item_table).get(ref[1])
            if e:
                return e
        self.fallbacks.add(const)
        return ("single", const.lower(), False)

    def all_ids(self):
        ids = set()
        for const in self.items_map:
            kind, val, _ = self.entry(const)
            if kind == "single":
                ids.add(val)
            elif kind == "color":
                ids.update(val.values())
            else:
                ids.update(val["weathering"] + val["waxed"])
        return ids


# ------------------------------------------------------------------ tab extraction
def parse_gameplay_order(tabs_src):
    m = re.search(r"gameplayColorOrder\s*=\s*List\.of\(([^;]*?)\)\s*;", tabs_src, re.S)
    if not m:
        sys.exit("ERROR: 'gameplayColorOrder' not found in CreativeModeTabs.java")
    return [c.lower() for c in re.findall(r"DyeColor\.([A-Z_]+)", m.group(1))]


def parse_copper_families(tabs_src):
    m = re.search(r"void\s+copperBlockFamilies\s*\([^)]*\)\s*\{", tabs_src)
    if not m:
        return []
    end = matching(tabs_src, m.end() - 1, "{", "}")
    return re.findall(r"Items\.([A-Z][A-Z0-9_]*)", tabs_src[m.end():end])


def tab_name(window, index):
    m = list(REGISTER_KEY.finditer(window))
    if m:
        return m[-1].group(1).split(".")[-1].lower()
    m = list(TITLE_KEY.finditer(window))
    if m:
        return m[-1].group(1).lower()
    return f"tab_{index}"


def scan_body(body, ctx):
    """Return ([(id, exact?)], [warnings]) for the body of one displayItems lambda."""
    R, result, warnings, pos = ctx["resolver"], [], [], 0

    def copper_ids(entry, which):
        if which == "all":
            parts = [entry[1][k] for k in ctx["copper_order"]]
            return [i for part in parts for i in part]
        return entry[1][which]

    while True:
        m = EVENT.search(body, pos)
        if not m:
            break
        if m.group("color"):
            const = m.group("color_c")
            e = R.entry(const)
            if e[0] != "color":
                warnings.append(f"registerColoredItems used with {const}, which is not a color collection")
            else:
                result += [(e[1][c], e[2]) for c in ctx["gameplay"]]
            pos = m.end()
        elif m.group("fam"):
            for const in ctx["families"]:
                e = R.entry(const)
                if e[0] == "copper":
                    result += [(i, e[2]) for i in copper_ids(e, m.group("fam_k"))]
                else:
                    warnings.append(f"copperBlockFamilies: Items.{const} is not a copper collection")
            pos = matching(body, body.index("(", m.start())) + 1
        else:
            const, ns = m.group("name"), m.group("ns")
            chain, after = method_chain(body, m.end())
            e = R.entry(const) if ns == "Items" else ("single", const.lower(), False)
            kind = e[0]
            if not chain:
                if kind != "single":
                    warnings.append(f"Items.{const} is a collection used without a method: skipped")
                else:
                    stmt_end = body.find(";", m.end())
                    tail = body[m.end(): stmt_end if stmt_end != -1 else len(body)]
                    if "PARENT_TAB_ONLY" not in tail:
                        result.append((e[1], e[2]))
                pos = m.end()
            elif chain == ["forEach"] and kind == "color":
                result += [(e[1][c], e[2]) for c in ctx["color_foreach"]]
                pos = after
            elif chain == ["forEach"] and kind == "copper":
                result += [(i, e[2]) for i in copper_ids(e, "all")]
                pos = after
            elif len(chain) == 1 and kind == "color" and camel_to_snake(chain[0]) in e[1]:
                result.append((e[1][camel_to_snake(chain[0])], e[2]))          # e.g. Items.WOOL.white()
                pos = after
            elif chain[:2] == ["waxed", "forEach"] and kind == "copper":
                result += [(i, e[2]) for i in copper_ids(e, "waxed")]
                pos = after
            elif chain == ["waxed", "unaffected"] and kind == "copper":
                result.append((e[1]["waxed"][0], e[2]))
                pos = after
            else:
                warnings.append(f"Items.{const}.{'.'.join(chain)}(...) not handled")
                pos = after
    return result, warnings


def extract_tabs(src, ctx):
    tabs, prev_end, idx = [], 0, 0
    for m in re.finditer(r"\.displayItems\s*\(", src):
        if m.start() < prev_end:
            continue
        open_paren = m.end() - 1
        close_paren = matching(src, open_paren)
        body = src[open_paren:close_paren]
        name = tab_name(src[prev_end:m.start()], idx)
        prev_end, idx = close_paren, idx + 1
        items, warnings = scan_body(body, ctx)
        dynamic = bool(re.search(r"\bgenerate\w*\(|acceptAll", body))
        tabs.append((name, items, warnings, dynamic))
    return tabs


def load_registry_ids(path):
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    return {k.split(":", 1)[-1] for k in data["minecraft:item"]["entries"]}


# ------------------------------------------------------------------ main
def run(input_dir, output_dir, registry=None, no_namespace=False, exclude_tabs=()):
    input_dir, output_dir = Path(input_dir), Path(output_dir)
    if not input_dir.is_dir():
        sys.exit(f"ERROR: input folder not found: {input_dir}")

    tabs_path = find_source(input_dir, "CreativeModeTabs.java")
    if tabs_path is None:
        sys.exit(f"ERROR: CreativeModeTabs.java not found under {input_dir}")
    paths = {
        "Items.java": find_source(input_dir, "Items.java", near=tabs_path),
        "BlockItemIds.java": find_source(input_dir, "BlockItemIds.java"),
        "ItemIds.java": find_source(input_dir, "ItemIds.java"),
    }
    for name, p in paths.items():
        if p is None:
            hint = " (it lives in net/minecraft/references: select the net/minecraft folder as input)" if name.endswith("Ids.java") else ""
            sys.exit(f"ERROR: {name} not found under {input_dir}{hint}")
    color_path = find_source(input_dir, "ColorCollection.java")
    copper_path = find_source(input_dir, "WeatheringCopperCollection.java")

    print(f"CreativeModeTabs : {tabs_path}", file=sys.stderr)
    for name, p in paths.items():
        print(f"{name:17}: {p}", file=sys.stderr)

    color_foreach, color_source = parse_color_foreach(color_path)
    prefixes, copper_order, copper_source = parse_copper_prefixes(copper_path)
    print(f"Color order      : {color_source}", file=sys.stderr)
    print(f"Copper prefixes  : {copper_source}\n", file=sys.stderr)

    tabs_src = read_java(tabs_path)
    block_table = parse_block_item_ids(read_java(paths["BlockItemIds.java"]), color_foreach, prefixes)
    item_table = parse_item_ids(read_java(paths["ItemIds.java"]), color_foreach)
    items_map = parse_items_java(read_java(paths["Items.java"]))
    resolver = Resolver(items_map, block_table, item_table)

    ctx = {
        "resolver": resolver,
        "gameplay": parse_gameplay_order(tabs_src),
        "families": parse_copper_families(tabs_src),
        "color_foreach": color_foreach,
        "copper_order": copper_order,
    }
    tabs = extract_tabs(tabs_src, ctx)
    if not tabs:
        sys.exit("ERROR: no .displayItems( call found; the file format differs from what was expected.")

    order, convention, seen = {}, set(), set()
    for name, items, warnings, dynamic in tabs:
        skipped = any(k in name.replace("_", "") for k in SKIP_TAB_KEYWORDS) or name in exclude_tabs
        added = 0
        if not skipped:
            for item, exact in items:
                if item not in seen:
                    seen.add(item)
                    order[item] = len(order)
                    added += 1
                    if not exact:
                        convention.add(item)
        note = ""
        if not skipped:
            if dynamic:
                note += "  [also has code-generated items, skipped]"
            if warnings:
                note += f"  [{len(set(warnings))} warnings]"
        status = "ignored" if skipped else f"{added} new"
        print(f"{name:22} {len(items):4} references, {status}{note}", file=sys.stderr)
        if not skipped:
            for w in sorted(set(warnings)):
                print(f"    WARNING: {w}", file=sys.stderr)

    print(f"\nTotal: {len(order)} items", file=sys.stderr)
    print(f"  ids read verbatim from BlockItemIds/ItemIds : {len(order) - len(convention)}", file=sys.stderr)
    print(f"  ids taken from the constant name (convention): {len(convention)}", file=sys.stderr)
    if resolver.fallbacks:
        print(f"  Items constants with no id symbol, name used  : {sorted(resolver.fallbacks)}", file=sys.stderr)

    # Sanity check: every item declared in Items.java that is NOT in the order must be explainable
    # (not in any creative tab, or generated by code). A normal block showing up here means a parsing problem.
    missing = sorted(resolver.all_ids() - set(order))
    print(f"\nItems.java declares {len(resolver.all_ids())} ids; {len(missing)} are not in the order "
          f"(expected: items outside the creative tabs or generated by code):", file=sys.stderr)
    print("  " + ", ".join(missing), file=sys.stderr)

    if registry:
        real = load_registry_ids(registry)
        bad = [i for i in order if i not in real]
        print(f"\nRegistry check: {len(bad)} ids do NOT exist in {registry}", file=sys.stderr)
        for i in bad[:60]:
            print(f"    ? {i}", file=sys.stderr)
    else:
        print("\nNo --registry given: ids were not checked against the real item registry.", file=sys.stderr)

    output_dir.mkdir(parents=True, exist_ok=True)
    out_path = output_dir / "creative_order.json"
    data = {(k if no_namespace else f"minecraft:{k}"): v for k, v in order.items()}
    out_path.write_text(json.dumps(data, indent=2), encoding="utf-8")
    print(f"Written: {out_path}", file=sys.stderr)


def main():
    ap = argparse.ArgumentParser(description="Extract the Creative inventory search-tab order from decompiled Minecraft sources.")
    ap.add_argument("-i", "--input", required=True, type=Path, help='decompiled "net/minecraft" folder')
    ap.add_argument("-o", "--output", required=True, type=Path, help="folder where creative_order.json is written")
    ap.add_argument("--registry", type=Path, help="reports/registries.json from the data generator, to verify ids")
    ap.add_argument("--no-namespace", action="store_true", help='write "oak_log" instead of "minecraft:oak_log"')
    ap.add_argument("--exclude-tab", action="append", default=[], help="tab name to drop (repeatable)")
    args = ap.parse_args()
    run(args.input, args.output, args.registry, args.no_namespace, args.exclude_tab)


if __name__ == "__main__":
    main()
